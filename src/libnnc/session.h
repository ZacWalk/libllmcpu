// nnc — sessions: one conversation's context, KV cache and sampler.
//
// The context is a token list whose first `cache.cur_pos` tokens have been
// run through the model. The rest are "pending": appended but not yet
// evaluated. Generation leaves its last token pending rather than paying a
// forward pass that may never be needed; the next call evaluates it first.
// `hidden` holds the model's final hidden state after the last evaluated
// token, from which the next token's logits are computed on demand.

#pragma once

#include "model.h"

#include <atomic>
#include <random>
#include <string>
#include <vector>

struct nnc_session
{
	const nnc_model* model = nullptr;
	model_kv_cache cache;
	std::vector<int> tokens; // the whole context
	std::vector<float> hidden; // [n_embd] after tokens[cache.cur_pos - 1]
	std::vector<float> logits; // [n_vocab]; also the argmax scratch
	bool have_hidden = false;
	bool logits_valid = false;
	// Recurrent models (Gated DeltaNet): `hidden` as it was when the cache's
	// state was last saved, at the start of a call spanning several batches,
	// so that a failed or cancelled call can put the session back (see
	// model_state_save).
	std::vector<float> saved_hidden;
	bool saved_have_hidden = false;
	std::string system_prompt;
	bool thinking = false; // chat turns let the model reason first (nnc_session_params.thinking)
	std::mt19937_64 rng;
	std::atomic<bool> cancel{false};

	// Generated bytes not yet passed to on_text (and to on_thinking): the
	// start of a character that a stopped generation cut in half, kept so
	// that a call carrying on from it can complete it.
	std::string text_pending;
	std::string thought_pending;

	// Sampler scratch, reused across tokens.
	std::vector<std::pair<float, int>> candidates;
	std::vector<float> probs;

	// MTP speculative decoding (optional). `dcache` reads `cache`, so the
	// session must not move once initialised.
	const nnc_model* draft = nullptr;
	model_kv_cache dcache;
	int n_draft = 0; // most tokens drafted per round
	std::vector<float> draft_h; // [n_embd] the drafter's recurrent input
	std::vector<int> verify_tokens; // [n_draft + 1] the token, then its drafts
	std::vector<float> verify_logits; // [(n_draft + 1) * n_vocab]
};

bool session_init(nnc_session& s, const nnc_model& m, const nnc_session_params& p);
void session_reset(nnc_session& s);

// MTP drafting: tokens drafted per round by default (fewer for a
// mixture-of-experts model, where every extra token checked reads experts
// of its own), and the probability below which the drafter's guess ends a
// round (a guess it is unsure of is rarely kept, and checking it costs more
// than it saves).
constexpr int SESSION_DRAFT_N = 4;
constexpr int SESSION_DRAFT_N_MOE = 2;
constexpr float SESSION_DRAFT_P_MIN = 0.7f;

nnc_status session_eval(nnc_session& s, const int* tokens, int n_tokens);
const float* session_logits(nnc_session& s);
int session_sample(nnc_session& s, const nnc_sampler_params& p);
nnc_status session_generate(nnc_session& s, const int* prompt, int n_prompt,
                            const nnc_generate_params& p, nnc_generate_result& r);
nnc_status session_chat(nnc_session& s, const std::string& message,
                        const nnc_generate_params& p, nnc_generate_result& r);
// A chat turn asking for `text` to be translated from `source` into
// `target` (language codes, or names for models without a language list).
nnc_status session_translate(nnc_session& s, const std::string& text, const std::string& source,
                             const std::string& target, const nnc_generate_params& p, nnc_generate_result& r);

// The tokens of one chat turn after `context`, the conversation so far:
// the system prompt on the first turn, or on later ones the end of a reply
// left open; then the user's `message` in the model's turn format, and the
// opening of the reply. `thinking` lets a model that can reason do so (see
// model_vocab::can_think).
std::vector<int> session_turn_tokens(const model_vocab& v, const std::vector<int>& context, const std::string& system,
                                     const std::string& message, bool thinking);

// Tells a reply's reasoning from its answer, token by token, by the model's
// thought markers (model_vocab::tok_thought_open / close). The markers show
// nowhere, and neither do the name line that opens a Gemma 4 thought channel
// or the newlines that open the reasoning and the answer after it.
struct thought_split
{
	int open = -1, close = -1;
	bool label = false; // a channel name line follows `open`
	bool inside = false; // in the reasoning
	bool skip_line = false; // dropping the channel name line
	bool trim = false; // dropping the newlines that open the reasoning or the answer

	// Carry on from the end of `context`: inside the reasoning when the last
	// marker in the current turn opened it.
	void start(const model_vocab& v, const std::vector<int>& context);
	// Whether `token` belongs to the reasoning; `text` gets the part of its
	// `piece` to show.
	bool route(int token, const std::string& piece, std::string& text);
};

// Move the longest complete, valid UTF-8 prefix of `pending` to the end of
// `out`, writing U+FFFD for each byte sequence that cannot form a character
// (the maximal-subpart rule decoders use). A character cut off by the end of
// `pending` stays there to be completed by later bytes; with `final` it
// becomes U+FFFD instead.
void utf8_take(std::string& pending, std::string& out, bool final);
